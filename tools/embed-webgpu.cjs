const fs = require('node:fs');
const modules = ['spot', 'spot-generate', 'spot-post', 'spot-prepare'];
let shader = modules.map(name => fs.readFileSync(`gpu/${name}.wgsl`, 'utf8')).join('\n');
// GPU search uses uniforms; final ray batches select immutable per-task data.
shader = shader.replace(/\bcfg\./g, 'configuration().')
  .replace(/\boffsets\[([^\]]+)\]/g, 'surfaceOffset($1)')
  .replaceAll('aimNodes[indices[i]]', 'aimNodeValue(indices[i])');
shader += `
var<private> taskConfiguration:Params;
var<private> taskConfigurationEnabled:bool=false;
var<private> taskOffsetsStart:u32=0u;
var<private> taskAimStart:u32=0u;
fn configuration()->Params { if(taskConfigurationEnabled){return taskConfiguration;}return cfg;}
fn surfaceOffset(i:u32)->u32{return offsets[i+select(0u,taskOffsetsStart,taskConfigurationEnabled)];}
fn aimNodeValue(i:u32)->vec4f{return aimNodes[i+select(0u,taskAimStart,taskConfigurationEnabled)];}
` + fs.readFileSync('gpu/spot-tasks.wgsl', 'utf8');
fs.writeFileSync('js/spot-webgpu-shader.js',
  '// Generated by node tools/embed-webgpu.cjs; do not edit.\nvar SPOT_GPU_SOURCE = ' + JSON.stringify(shader) + ';\n');
fs.writeFileSync('js/spot-display-shader.js',
  '// Generated by node tools/embed-webgpu.cjs; do not edit.\nvar SPOT_DISPLAY_SOURCE = ' +
  JSON.stringify(fs.readFileSync('gpu/spot-display.wgsl', 'utf8')) + ';\n');
